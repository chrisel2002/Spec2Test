import { strToU8, zipSync } from "fflate";

import {
  groupTestsByRequirement,
  type ExportInput,
  originalText,
  slugify,
} from "./shared";

export type GeneratedFile = { path: string; content: string };

// Every way a line can end in source text, including the Unicode line and
// paragraph separators, which JavaScript also treats as line terminators:
// left inside a // comment, they would end it early and turn the rest of the
// requirement text into code.
const LINE_BREAK = /\r\n|\r|\n|\u2028|\u2029/;

// Text from the spec or a reviewer, as // comment lines. Each line is its
// own comment, so no input can break out of the comment.
function comment(text: string, indent: string, firstPrefix = ""): string[] {
  return `${firstPrefix}${text}`
    .split(LINE_BREAK)
    .map((line) => `${indent}// ${line}`.trimEnd());
}

// A TypeScript string literal. JSON's string syntax is valid TS and escapes
// quotes, backslashes, and control characters for us.
function literal(text: string): string {
  return JSON.stringify(text);
}

// One Playwright spec file per requirement with at least one approved test:
// a describe block named after the requirement, and a test.fixme per
// approved test with its Given/When/Then as comments. test.fixme makes
// Playwright report the tests as "to do" instead of failing, so the
// skeletons can be committed before anyone has implemented them.
export function buildPlaywrightFiles(
  { detail, documentFilename }: ExportInput,
  { sourceUrl }: { sourceUrl: string },
): GeneratedFile[] {
  return groupTestsByRequirement(detail).flatMap(({ requirement, testCases }) => {
    const approved = testCases.filter((tc) => tc.status === "approved");
    if (approved.length === 0) return [];

    const describeName = `${requirement.code}: ${requirement.title}`;
    const lines = [
      "// Generated by Spec2Test from approved test cases.",
      "// Implement each test, then change test.fixme to test so it runs.",
      "//",
      ...comment(describeName, ""),
      ...comment(requirement.text, "", "Requirement: "),
      ...(requirement.ambiguityResolved
        ? comment(originalText(requirement), "", "Originally (ambiguous): ")
        : []),
      ...comment(`${documentFilename}, reviewed in ${sourceUrl}`, "", "Source: "),
      "",
      'import { test } from "@playwright/test";',
      "",
      `test.describe(${literal(describeName)}, () => {`,
    ];

    approved.forEach((tc, i) => {
      if (i > 0) lines.push("");
      lines.push(
        `  test.fixme(${literal(`${tc.label}: ${tc.title}`)}, async ({ page }) => {`,
        ...comment(tc.given, "    ", "Given "),
        ...comment(tc.when, "    ", "When "),
        ...comment(tc.then, "    ", "Then "),
        "    void page; // keeps linters quiet until the test uses page",
        "  });",
      );
    });
    lines.push("});", "");

    return [
      {
        path: `${requirement.code.toLowerCase()}-${slugify(requirement.title)}.spec.ts`,
        content: lines.join("\n"),
      },
    ];
  });
}

export function zipFiles(folder: string, files: GeneratedFile[]): Uint8Array {
  return zipSync(
    Object.fromEntries(files.map((file) => [`${folder}/${file.path}`, strToU8(file.content)])),
  );
}
